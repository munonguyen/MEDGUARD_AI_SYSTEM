const scene=new Object3D(),bones={},values={};
const vrm={scene,meta:{metaVersion:'1'},humanoid:{getNormalizedBoneNode:n=>{if(!bones[n]){const b=bones[n]=new Object3D();b.name=n;scene.add(b);}return bones[n];}},expressionManager:{expressionMap:{},setValue:(n,v)=>values[n]=v},update(){}};
const motion=new DoctorMotion(vrm,'dr_mai',{random:()=>.4});motion.startUtterance('Tôi sẽ giải thích.');motion.beginSpeechSegment('Tôi sẽ giải thích.',timing);
for(let i=0;i<60;i++)motion.update(1/60,{speaking:true,hasAudio:true,audioLevel:.1,playbackTime:1.5,playbackDuration:4,visemes:{aa:0,ou:.4}});
