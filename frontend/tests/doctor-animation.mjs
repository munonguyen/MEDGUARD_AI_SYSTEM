assert(motion.cueAt(true,false,9,20).rest,'long sentence settles rather than looping gestures');
const layer=new DoctorAnimationLayer(vrm);layer.loaded=true;
const clip=new AnimationClip('explain',1,[new QuaternionKeyframeTrack('chest.quaternion',[0,.5,1],[0,0,0,1,...new Quaternion().setFromAxisAngle({x:0,y:1,z:0},.05).toArray(),0,0,0,1])]);
